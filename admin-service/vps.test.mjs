import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, cp, symlink, readFile, realpath, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { createStore } from './local-store.mjs';

const source = process.env.SITE_SOURCE;
if (!source) throw new Error('Informe SITE_SOURCE.');
const temp = await mkdtemp(join(tmpdir(), 'rdc-test-')), state = join(temp, 'state'), initial = join(state, 'releases', 'initial');
await mkdir(initial, { recursive: true });
for (const file of ['fechaduras-eletronicas.html', 'fechaduras-jbm.html', 'fechaduras-mecanicas-stam.html', 'produto-fechadura-athenas.html', 'produto-fechadura-athenas-vidro.html']) await cp(join(source, file), join(initial, file));
await symlink('releases/initial', join(state, 'current'));
const store = createStore(state);
test('salvamento atômico mantém a versão anterior e é idempotente', async () => {
  const base = await store.snapshot(), before = await readFile(join(initial, 'produto-fechadura-athenas.html'), 'utf8');
  const changes = [{ id: 'produto-fechadura-athenas', priceCents: 72500 }, { id: 'produto-fechadura-athenas-vidro', priceCents: 73500 }];
  const result = await store.save({ revision: base.revision, changes });
  assert.equal(result.unchanged, false);
  const current = await store.snapshot();
  assert.equal(current.products.find(p => p.id === changes[0].id).priceCents, 72500);
  assert.equal(current.products.find(p => p.id === changes[1].id).priceCents, 73500);
  assert.equal(await readFile(join(initial, 'produto-fechadura-athenas.html'), 'utf8'), before);
  assert.equal((await readFile(join(current.directory, 'produto-fechadura-athenas.html'), 'utf8')).match(/R\$ 725,00/g).length, 2);
  const repeat = await store.save({ revision: base.revision, changes });
  assert.equal(repeat.unchanged, true); assert.equal(repeat.revision, result.revision);
  await assert.rejects(store.save({ revision: base.revision, changes: [{ id: changes[0].id, priceCents: 71000 }] }), e => e.status === 409);
});
test('falha de validação não publica alteração parcial', async () => {
  const base = await store.snapshot();
  await assert.rejects(store.save({ revision: base.revision, changes: [{ id: 'produto-fechadura-athenas', priceCents: 70000 }, { id: 'desconhecido', priceCents: 50 }] }));
  assert.equal((await store.snapshot()).revision, base.revision);
});
test('parcelas persistem por produto, sem mudar preço, e repetição é idempotente', async () => {
  const base = await store.snapshot(), product = base.products.find(p => p.id === 'produto-fechadura-athenas');
  const before = await readFile(join(base.directory, product.id + '.html'), 'utf8');
  const changes = [{ id: product.id, installments: 3 }];
  const saved = await store.save({ revision: base.revision, changes });
  const current = await createStore(state).snapshot();
  const updated = current.products.find(p => p.id === product.id);
  assert.equal(updated.installments, 3); assert.equal(updated.priceCents, product.priceCents);
  assert.equal(current.products.find(p => p.id === 'produto-fechadura-athenas-vidro').installments, 5);
  assert.equal(await readFile(join(base.directory, product.id + '.html'), 'utf8'), before);
  assert.equal((await store.save({ revision: base.revision, changes })).unchanged, true);
  assert.equal((await store.snapshot()).revision, saved.revision);
  await assert.rejects(store.save({ revision: base.revision, changes: [{ id: product.id, installments: 8 }] }), e => e.status === 409);
});
test('preço e parcelas de dois produtos são publicados juntos; lote inválido não altera nada', async () => {
  const base = await store.snapshot();
  const changes = [{ id: 'produto-fechadura-athenas', priceCents: 73100, installments: 7 }, { id: 'produto-fechadura-athenas-vidro', installments: 9 }];
  await store.save({ revision: base.revision, changes });
  const current = await store.snapshot();
  assert.equal(current.products.find(p => p.id === changes[0].id).priceCents, 73100);
  assert.equal(current.products.find(p => p.id === changes[0].id).installments, 7);
  assert.equal(current.products.find(p => p.id === changes[1].id).installments, 9);
  for (const p of current.products.filter(p => !changes.some(c => c.id === p.id))) assert.deepEqual(p, base.products.find(original => original.id === p.id));
  await assert.rejects(store.save({ revision: current.revision, changes: [{ id: changes[0].id, installments: 4 }, { id: changes[1].id, installments: 25 }] }));
  assert.equal((await store.snapshot()).revision, current.revision);
});
test('API protege login, origem, arquivos privados e revogação da sessão', async () => {
  const setupToken = 'fixture-activation-token-not-a-real-secret';
  process.env.STATE_ROOT = state; process.env.NODE_ENV = 'test'; process.env.PUBLIC_ORIGIN = 'http://localhost:3010';
  process.env.ADMIN_SETUP_TOKEN_SHA256 = createHash('sha256').update(setupToken).digest('hex');
  const { server } = await import('./server-vps.mjs');
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const url = `http://127.0.0.1:${server.address().port}`;
  const post = (path, data, cookie, origin = 'http://localhost:3010') => fetch(url + path, { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: origin, ...(cookie ? { Cookie: cookie } : {}) }, body: JSON.stringify(data) });
  try {
    assert.equal((await fetch(url + '/api/products')).status, 401);
    assert.equal((await fetch(url + '/.git/config')).status, 404);
    assert.equal((await fetch(url + '/admin-service/server-vps.mjs')).status, 404);
    assert.equal((await fetch(url + '/private/password.json')).status, 404);
    const pw = 'fixture-password-not-real-2026';
    const initial = { username: 'admin', password: 'admin' };
    assert.equal((await post('/api/login', initial, '', 'https://attacker.invalid')).status, 403);
    assert.equal((await post('/api/login', { username: 'admin', password: 'wrong' })).status, 401);
    const activation = await post('/api/login', initial);
    assert.equal(activation.status, 200);
    assert.equal((await activation.clone().json()).mustChangeCredentials, false);
    let cookie = activation.headers.get('set-cookie').split(';')[0];
    assert.match(activation.headers.get('set-cookie'), /HttpOnly/); assert.match(activation.headers.get('set-cookie'), /SameSite=Strict/);
    assert.equal((await fetch(url + '/api/products', { headers: { Cookie: cookie } })).status, 200);
    await assert.rejects(readFile(join(state, 'private', 'password.json'), 'utf8'), { code: 'ENOENT' });
    assert.equal((await post('/api/account', { username: 'owner', currentPassword: 'wrong', password: pw }, cookie)).status, 400);
    assert.equal((await post('/api/account', { username: 'owner', currentPassword: 'admin', password: 'admin' }, cookie)).status, 400);
    const configured = await post('/api/account', { username: 'owner', currentPassword: 'admin', password: pw }, cookie);
    assert.equal(configured.status, 200);
    cookie = configured.headers.get('set-cookie').split(';')[0];
    assert.equal((await post('/api/login', initial)).status, 401);
    const creds = JSON.parse(await readFile(join(state, 'private', 'password.json'), 'utf8'));
    assert.notEqual(creds.hash, pw); assert.ok(creds.salt);
    assert.equal(creds.username, 'owner');
    const result = await fetch(url + '/api/products', { headers: { Cookie: cookie } }); assert.equal(result.status, 200);
    const catalog = await result.json(); assert.equal(catalog.products.length, 23);
    const target = catalog.products.find(p => p.id === 'produto-fechadura-athenas');
    const installmentChange = { revision: catalog.revision, changes: [{ id: target.id, installments: 4 }] };
    assert.equal((await post('/api/prices', installmentChange)).status, 401);
    const savedInstallments = await post('/api/prices', installmentChange, cookie);
    assert.equal(savedInstallments.status, 200);
    const savedCatalog = await (await fetch(url + '/api/products', { headers: { Cookie: cookie } })).json();
    assert.equal(savedCatalog.products.find(p => p.id === target.id).installments, 4);
    assert.equal(savedCatalog.products.find(p => p.id === target.id).priceCents, target.priceCents);
    assert.equal((await post('/api/prices', { revision: savedCatalog.revision, changes: [{ id: target.id, installments: 25 }] }, cookie)).status, 400);
    assert.equal((await post('/api/prices', {}, cookie, 'https://attacker.invalid')).status, 403);
    assert.equal((await post('/api/account', { username: 'new-owner', currentPassword: 'incorrect', password: 'new-fixture-password-2026' }, cookie)).status, 400);
    const changed = await post('/api/account', { username: 'new-owner', currentPassword: pw, password: 'new-fixture-password-2026' }, cookie);
    assert.equal(changed.status, 200);
    assert.equal((await fetch(url + '/api/products', { headers: { Cookie: cookie } })).status, 401);
    cookie = changed.headers.get('set-cookie').split(';')[0];
    assert.equal((await post('/api/logout', {}, cookie)).status, 200);
    assert.equal((await fetch(url + '/api/products', { headers: { Cookie: cookie } })).status, 401);
    assert.equal((await post('/api/login', { username: 'owner', password: pw })).status, 401);
    assert.equal((await post('/api/login', { username: 'admin', password: 'admin' })).status, 401);
    assert.equal((await post('/api/login', { username: 'new-owner', password: 'new-fixture-password-2026' })).status, 200);
    assert.equal((await post('/api/login', null)).status, 400);
    // Failed attempts from one visitor must not lock every visitor behind Nginx.
    const invalidFrom = (ip) => fetch(url + '/api/login', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'http://localhost:3010', 'X-Real-IP': ip }, body: JSON.stringify({ username: 'invalid', password: 'incorrect' }) });
    for (let i = 0; i < 10; i++) assert.equal((await invalidFrom('192.0.2.10')).status, 401);
    assert.equal((await invalidFrom('192.0.2.10')).status, 429);
    assert.equal((await invalidFrom('192.0.2.11')).status, 401);

  } finally { await new Promise(resolve => server.close(resolve)); await rm(temp, { recursive: true, force: true }); }
});
